RANK_RUBY = [1786, 1788, 1790, 1792, 1794, 1796, 1798, 1800]


def main():
    ents = read_entries(open(os.path.join(HERE, "..", "san9pk", "M_MSG.S9"), "rb").read())

    def jp(i):
        t = re.sub(r"\{ESC:[HK]\}", "", decode(ents[i][1]))
        assert t.endswith("{05}{05}{05}"), i
        return t[:-12]

    out = ["# 고유명사 (make_names.py 로 생성). 한자 독음, 성씨·지명 첫 글자 두음법칙.",
           "# 지명: 이름 교체 + 읽기(루비) 비움 / 인물: 성·이름·자 교체, 읽기는 정렬용으로 유지", ""]

    def block(i, ko, kind="name", loose=False):
        j = jp(i)
        if not j:
            return
        out.append("[M %d %s]" % (i, kind))
        out.append("JP " + j)
        out.append(("KO! " if loose else "KO ") + ko)
        out.append("")

    def place_blocks(start, names):
        for n, ko in enumerate(names):
            i = start + 2 * n
            if jp(i) == "なし":
                raise SystemExit("빈 자리 #%d" % i)
            block(i, ko, loose="{U:" in jp(i))
            ruby = jp(i + 1)
            if not ruby.startswith("{ESC:k}"):
                raise SystemExit("읽기 항목 아님 #%d %r" % (i + 1, ruby))
            block(i + 1, "{ESC:k}")

    out.append("# --- 주·지역·거점")
    place_blocks(136, PLACES)
    out.append("# --- 도시")
    place_blocks(723, CITIES)
    out.append("# --- 관작 읽기(루비) 비움")
    for i in RANK_RUBY:
        block(i, "{ESC:k}")
    out.append("# --- 인물")
    for k, (sur, giv, azana) in sorted(PERSONS.items()):
        b = 1811 + 4 * k
        for i, ko in ((b, sur), (b + 1, giv), (b + 2, azana)):
            if ko:
                block(i, ko, loose="{U:" in jp(i))
            elif jp(i):
                raise SystemExit("자 번역 누락: 인물 %d #%d %r" % (k, i, jp(i)))
    assert len(PLACES) == 152 and len(CITIES) == 50, (len(PLACES), len(CITIES))
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("->", OUT)


if __name__ == "__main__":
    main()
