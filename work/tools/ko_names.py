def to_hanja(s):
    s = re.sub(r"\{U:(F[0-9A-F]{3})\}", lambda m: UMAP.get(m.group(1), "?"), s)
    return re.sub(r"\{S:(F[0-9A-F]{3})\}", lambda m: SMAP.get(m.group(1), "?"), s)


def char_reading(ch):
    if ch in CHAR_FIX:
        return CHAR_FIX[ch]
    r = hanja.translate(ch, "combination-text")
    r = re.sub(r"[^가-힣]", "", hanja.translate(ch, "substitution"))
    return r or "?"


def raw_reading(s):
    """두음법칙 없이 글자별 본음."""
    out = []
    for ch in s:
        if ch in CHAR_FIX:
            out.append(CHAR_FIX[ch])
            continue
        # hanja 패키지는 단독 글자에 두음법칙을 적용하므로 앞에 더미 글자를 붙여 본음을 얻는다
        r = hanja.translate("一" + ch, "substitution")[1:]
        out.append(r if re.fullmatch(r"[가-힣]", r) else "?")
    return "".join(out)


def yeol_rule(r):
    """모음이나 ㄴ 받침 뒤의 '렬·률'은 '열·율' (한글 맞춤법 제11항)."""
    out = list(r)
    for i in range(1, len(out)):
        if out[i] in ("렬", "률"):
            prev = ord(out[i - 1]) - 0xAC00
            if 0 <= prev < 11172 and prev % 28 in (0, 4):
                out[i] = "열" if out[i] == "렬" else "율"
    return "".join(out)


def word_reading(s, surname=False):
    """단어 독음: 본음 + 첫 글자 두음법칙 (+ 성씨 특례)."""
    s = to_hanja(s)
    if not s:
        return ""
    r = raw_reading(s)
    first = s[0]
    if surname and first in SURNAME_FIX:
        return SURNAME_FIX[first] + r[1:]
    if r and r[0] in INITIAL:
        r = INITIAL[r[0]] + r[1:]
    return yeol_rule(r)
